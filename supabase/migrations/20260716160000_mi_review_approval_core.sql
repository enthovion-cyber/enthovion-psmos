create table if not exists public.mi_approval_instances (
  id uuid primary key default gen_random_uuid(),
  company_id text not null references public."Tenant"("id") on delete cascade,
  site_id text not null,
  approval_number text not null,
  source_module text not null,
  source_record_id text not null,
  source_record_number text null,
  equipment_id text null references public."Equipment"("id") on delete set null,
  approval_type text not null default 'Standard Review',
  current_stage text not null default 'Submitted',
  status text not null default 'Submitted',
  priority text not null default 'Normal',
  risk_level text null,
  safety_critical boolean not null default false,
  psm_critical boolean not null default false,
  readiness_impact boolean not null default false,
  startup_blocker boolean not null default false,
  e_signature_required boolean not null default false,
  submitted_by text not null references public."User"("id") on delete restrict,
  submitted_at timestamptz not null default now(),
  due_at timestamptz null,
  completed_at timestamptz null,
  cancelled_at timestamptz null,
  cancellation_reason text null,
  workflow_instance_id text null references public.workflow_instances(id) on delete set null,
  stale_approval boolean not null default false,
  last_validation_status text not null default 'Not Run',
  last_action text null,
  created_by text null references public."User"("id") on delete set null,
  updated_by text null references public."User"("id") on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mi_approval_instances_number_unique unique (company_id, site_id, approval_number),
  constraint mi_approval_instances_status_check check (status in ('Draft','Submitted','Pending Approval','In Review','Approved','Approved With Conditions','Rejected','Returned for Correction','More Information Requested','Delegated','Escalated','Cancelled','Superseded','Completed','Expired / Overdue')),
  constraint mi_approval_instances_priority_check check (priority in ('Low','Normal','Medium','High','Critical','Emergency')),
  constraint mi_approval_instances_last_validation_check check (last_validation_status in ('Not Run','Passed','Warning','Failed','Overridden'))
);

