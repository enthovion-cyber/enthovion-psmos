  delegated_to_user_id text null references public."User"("id") on delete set null,
  status text not null default 'Pending',
  due_at timestamptz null,
  acted_by text null references public."User"("id") on delete set null,
  acted_at timestamptz null,
  action text null,
  comments text null,
  e_signature_id text null references public.electronic_signatures(id) on delete set null,
  workflow_step_id text null references public.workflow_instance_steps(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mi_approval_stages_unique_stage unique (approval_instance_id, stage_number, stage_name),
  constraint mi_approval_stages_status_check check (status in ('Pending','In Progress','Approved','Rejected','Returned','Skipped','Delegated','Escalated','Cancelled'))
);

